/**
 * Mapa indexado por ID para búsqueda directa O(1).
 */
export const COMMERCIAL_RUBROS_MAP: Record<CommercialRubroId, CommercialRubro> =
  COMMERCIAL_RUBROS.reduce(
    (acc, rubro) => {
      acc[rubro.id] = rubro;
      return acc;
    },
    {} as Record<CommercialRubroId, CommercialRubro>
  );

/**
 * Identificador de rubro predeterminado cuando un comercio no tiene rubro especificado.
 */
export const DEFAULT_COMMERCIAL_RUBRO_ID: CommercialRubroId = 'comercio_general';

/**
 * Obtiene la configuración completa de un rubro con respaldo defensivo en 'comercio_general'.
 */
export function getCommercialRubro(id?: CommercialRubroId | string | null): CommercialRubro {
  if (id && id in COMMERCIAL_RUBROS_MAP) {
    return COMMERCIAL_RUBROS_MAP[id as CommercialRubroId];
  }
  return COMMERCIAL_RUBROS_MAP[DEFAULT_COMMERCIAL_RUBRO_ID];
}
